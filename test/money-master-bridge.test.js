const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { existsSync } = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const os = require('node:os');
const { spawn, spawnSync } = require('node:child_process');
const { once } = require('node:events');
const { buildPlan, LEDGERS, financialDigest, digest } = require('../money-master');
const bridgeSource = path.resolve(__dirname, '../../accountant/v2/api/stripe_sync.php');
const canRun = existsSync(bridgeSource) && spawnSync('php', ['--version']).status === 0;

test('real PHP bridge: authentication, balanced storage, receipts, conflicts and rollback', { skip: !canRun }, async (t) => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'stripe-bridge-test-'));
  t.after(() => fs.rm(temporary, { recursive: true, force: true }));
  const stateFile = path.join(temporary, 'state.json');
  const readState = async () => JSON.parse(await fs.readFile(stateFile, 'utf8'));
  const writeState = (state) => fs.writeFile(stateFile, JSON.stringify(state));
  await writeState({ transactions: [], receipts: {} });
  await fs.copyFile(bridgeSource, path.join(temporary, 'stripe_sync.php'));
  await fs.copyFile(path.join(__dirname, 'fixtures/money-master-connect.php'), path.join(temporary, 'connect.php'));
  await fs.writeFile(path.join(temporary, 'stripe_sync_config.php'), "<?php return ['token' => 'fixture-token-at-least-32-characters', 'currency' => 'aed', 'created_by' => 68, 'allow_test' => false];\n");
  const probe = http.createServer(); probe.listen(0, '127.0.0.1'); await once(probe, 'listening');
  const port = probe.address().port; await new Promise((resolve) => probe.close(resolve));
  const child = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', temporary], { env: { ...process.env, STRIPE_SYNC_TOKEN: '', STRIPE_SYNC_CURRENCY: 'aed', STRIPE_SYNC_ALLOW_TEST: '0', STRIPE_SYNC_CREATED_BY: '68', SYNC_TEST_STATE: stateFile, SYNC_TEST_LEDGERS: JSON.stringify(LEDGERS) }, stdio: 'ignore' });
  t.after(() => child.kill());
  const url = `http://127.0.0.1:${port}/stripe_sync.php`;
  const api = async (entry, token = 'fixture-token-at-least-32-characters', options = {}) => {
    const response = await fetch(url, { headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(entry ? { method: 'POST', body: JSON.stringify({ payload: JSON.stringify(entry), ...options }) } : {}) });
    return { status: response.status, body: await response.json() };
  };
  for (let i = 0; i < 100; i++) { try { await api(); break; } catch { await new Promise((resolve) => setTimeout(resolve, 20)); } }
  assert.equal((await api(undefined, 'bad-token')).status, 401);
  const missing = await fetch(url);
  assert.equal(missing.status, 401);
  assert.equal((await missing.json()).code, 'missing_token');
  const fallback = await fetch(url, { headers: { 'X-Money-Master-Sync-Token': 'fixture-token-at-least-32-characters' } });
  assert.equal(fallback.status, 200, 'dedicated token header works when Authorization is stripped');
  assert.equal((await fallback.json()).ok, true);
  const wrongFallback = await fetch(url, { headers: { 'X-Money-Master-Sync-Token': 'wrong-token' } });
  assert.equal(wrongFallback.status, 401);
  assert.equal((await wrongFallback.json()).code, 'invalid_token');
  assert.equal((await api()).body.receipts.length, 0);
  assert.equal((await api()).body.pending_entries, true);
  assert.equal((await api()).body.journal_version, 2);
  const row = { id: 'li_one', kind: 'payment', source_id: 'ch_one', payment_intent: 'pi_one', product_id: 'prod_one', product: 'Sentink Starter', customer_name: 'Jane Buyer', customer_email: 'jane@example.com', status: 'paid', amount: 10001, currency: 'aed', settle_gross: 10001, settle_currency: 'aed', created: 1780000000 };
  let entry = buildPlan({ allRows: [row], visibleRows: [row], payouts: [], contents: {}, mappings: { prod_one: 31758077 }, account: 'acct_fixture', mode: 'live' }).entries[0];
  assert.equal((await api({ ...entry, login_center: 4 })).status, 400);
  assert.equal((await api({ ...entry, mode: 'test', key: entry.key.replace(':live:', ':test:') })).status, 400);
  assert.equal((await api({ ...entry, approval: 'approved' })).status, 400);
  const invalid = structuredClone(entry); invalid.lines[0].debit++;
  assert.equal((await api(invalid)).status, 400);
  const failedState = await readState(); failedState.fail_on_ledger = 31758077; await writeState(failedState);
  assert.equal((await api(entry)).status, 503);
  assert.equal((await readState()).transactions.length, 0, 'first line rolls back if the second insert fails');
  failedState.fail_on_ledger = null; await writeState(failedState);
  const posted = await api(entry);
  assert.equal(posted.status, 200); assert.equal(posted.body.status, 'posted');
  let saved = await readState();
  assert.equal(saved.transactions.length, 2);
  assert.ok(saved.transactions.every(row => row.approved === 0), 'every imported line is Pending');
  assert.ok(saved.transactions.every(row => row.reason.includes('Jane Buyer') && row.reason.includes('jane@example.com')));
  assert.equal(saved.transactions[0].debit, '100.01');
  assert.equal(saved.transactions[1].opposite_ledger, 31758052);
  assert.equal((await api(entry)).body.status, 'synced');
  assert.equal((await readState()).transactions.length, 2);
  assert.equal((await api()).body.receipts[0].intact, true);
  assert.equal((await api()).body.receipts[0].financial_hash, financialDigest(entry), 'PHP and JavaScript financial checksums agree');
  // A legacy receipt is upgraded only through the reviewed metadata path.
  const legacy = { ...entry, reason: 'Legacy Stripe payment memo' };
  delete legacy.version; delete legacy.approval;
  saved.transactions.forEach(row => { row.approved = 1; row.reason = legacy.reason; });
  saved.receipts[entry.key].payload = JSON.stringify(legacy);
  saved.receipts[entry.key].payload_hash = digest(legacy);
  await writeState(saved);
  assert.equal((await api(entry)).status, 409);
  saved.fail_receipt_update = true; await writeState(saved);
  assert.equal((await api(entry, undefined, { upgrade_metadata: true })).status, 503);
  const rolledBack = await readState();
  assert.ok(rolledBack.transactions.every(row => row.approved === 1 && row.reason === legacy.reason), 'failed receipt upgrade rolls back memo and approval changes');
  saved.fail_receipt_update = false; await writeState(saved);
  const upgraded = await api(entry, undefined, { upgrade_metadata: true });
  assert.equal(upgraded.body.status, 'updated');
  saved = await readState();
  assert.equal(saved.transactions.length, 2);
  assert.ok(saved.transactions.every(row => row.approved === 0 && row.reason === entry.reason));
  const changedFinancials = structuredClone(entry);
  changedFinancials.lines[0].debit++; changedFinancials.lines[1].credit++;
  assert.equal((await api(changedFinancials, undefined, { upgrade_metadata: true })).status, 409, 'metadata updates cannot change ledger amounts');
  saved.transactions.forEach(row => { row.approved = 1; }); await writeState(saved);
  assert.equal((await api()).body.receipts[0].intact, true);
  assert.equal((await api(entry)).body.status, 'synced');
  assert.ok((await readState()).transactions.every(row => row.approved === 1), 'later manual approvals survive repeated syncs');
  saved.transactions[0].deleted = 1; await writeState(saved);
  assert.equal((await api()).body.receipts[0].intact, false);
  assert.equal((await api()).body.receipts[0].restorable, false, 'partially deleted journals require manual review');
  assert.equal((await api(entry)).status, 409);
  assert.equal((await readState()).transactions.length, 2);
  saved.transactions[1].deleted = 1; await writeState(saved);
  assert.equal((await api()).body.receipts[0].restorable, true);
  assert.equal((await api(entry)).status, 409, 'restoration requires the explicit reviewed request flag');
  const restored = await api(entry, undefined, { restore_deleted: true });
  assert.equal(restored.status, 200); assert.equal(restored.body.status, 'restored');
  assert.equal((await readState()).transactions.length, 2, 'restoring must reuse the original financial rows');
  assert.ok((await readState()).transactions.every(row => row.approved === 0), 'restored entries return as Pending');
  assert.equal((await api()).body.receipts[0].intact, true);
  assert.equal((await api(entry)).body.status, 'synced');
  const duplicate = await readState();
  duplicate.transactions.forEach((row) => { row.deleted = 1; });
  duplicate.transactions.push({ ...duplicate.transactions[0], id: 3, deleted: 0 });
  await writeState(duplicate);
  assert.equal((await api()).body.receipts[0].restorable, false, 'an active copy with the same reference blocks restoration');
  assert.equal((await api(entry, undefined, { restore_deleted: true })).status, 409);
});
